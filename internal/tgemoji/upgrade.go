// UpgradeEmoji wraps some of the emoji in text with <tg-emoji> tags so they
// render as animated premium emoji. It picks roughly probability fraction of
// the eligible emoji (default 30%). The original emoji is always kept as the
// fallback inside the tag, so non-premium clients still see it.
//
// Emoji already inside <tg-emoji>...</tg-emoji> or other HTML tags are left
// untouched.
func UpgradeEmoji(text string, probability ...float64) string {
	p := 1.0
	if len(probability) > 0 && probability[0] >= 0 && probability[0] <= 1 {
		p = probability[0]
	}
	if len(RestrictedEmojiPack) == 0 || p <= 0 {
		return text
	}

	var b strings.Builder
	b.Grow(len(text) + len(text)/4)

	runes := []rune(text)
	i := 0
	insideTgEmoji := false
	for i < len(runes) {
		r := runes[i]

		// Skip HTML tags entirely.
		if r == '<' {
			end := indexOfRune(runes, '>', i)
			if end > i {
				tagContent := string(runes[i : end+1])
				b.WriteString(tagContent)
				if strings.HasPrefix(tagContent, "<tg-emoji") {
					insideTgEmoji = true
				} else if strings.HasPrefix(tagContent, "</tg-emoji>") {
					insideTgEmoji = false
				}
				i = end + 1
				continue
			}
		}

		// Don't wrap emoji that are already inside a <tg-emoji> tag.
		if insideTgEmoji {
			b.WriteRune(r)
			i++
			continue
		}

		// Try multi-rune emoji first (e.g. family emoji have up to 7 runes).
		matched := false
		for l := min(7, len(runes)-i); l >= 1; l-- {
			candidate := string(runes[i : i+l])
			if id, ok := RestrictedEmojiPack[candidate]; ok {
				if rand.Float64() < p {
					b.WriteString(Tag(id, candidate))
				} else {
					b.WriteString(candidate)
				}
				i += l
				matched = true
				break
			}
		}
		if !matched {
			b.WriteRune(r)
			i++
		}
	}
	return b.String()
}

// indexOfRune returns the index of r in s starting from start, or -1.
func indexOfRune(s []rune, r rune, start int) int {
	for i := start; i < len(s); i++ {
		if s[i] == r {
			return i
		}
	}
	return -1
}
